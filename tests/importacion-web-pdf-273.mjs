import {esFilaImpuestoGenerador} from '../js/importacion-web-pdf/pdf.js';
import assert from 'node:assert/strict';
import {prepararImportacion,validarEntrada,elegirDestino,fechaISO,pesos,conceptoDIAN} from '../js/importacion-web-pdf/modelo.js';
const base={fuente:'PDF_1116',nit:'900123456',razonSocial:'PRUEBA S.A.S.',concepto:'Impuesto sobre la renta y complementarios',anio:2024,periodo:1,numeroObligacion:'100100000000001',cuotas:[{numero:1,fecha:'2025-09-19',impuesto:200000},{numero:2,fecha:'2025-10-19',impuesto:300000}]};
const original={pagos:[],vencimientos:[]},before=JSON.stringify(original);
const pdf=prepararImportacion(original,base).datos;
assert.equal(JSON.stringify(original),before);
assert.deepEqual(pdf.vencimientos.map(v=>v.impuesto),[200000,300000]);
const solo={...base,cuotas:[],sancion:{valor:524000,fecha:'2026-09-30'}};
assert.equal(prepararImportacion({},solo).datos.vencimientos.length,0);
assert.equal(prepararImportacion({valorSancion:20,tieneSancion:'SI',fechaSancion:'2024-01-01'},base).datos.valorSancion,20);
assert.throws(()=>prepararImportacion({nit:'900999999'},base),/contribuyente/);
assert.throws(()=>validarEntrada({...base,fuente:'WEB_MUISCA'}),/Origen/);
assert.throws(()=>validarEntrada({...base,pagos:[{recibo:'4900000000001'}]}),/no importa recibos/);
assert.throws(()=>validarEntrada({...base,cuotas:[base.cuotas[0],base.cuotas[0]]}),/repetido/);
assert.throws(()=>fechaISO('31/02/2026'));assert.throws(()=>pesos('1,23'));assert.throws(()=>pesos('-10'));
assert.throws(()=>elegirDestino({obligaciones:[{id:'a'},{id:'b'}]},base),/destino/);
assert.equal(elegirDestino({obligaciones:[{id:'a'},{id:'b'}]},base,'b').id,'b');
console.log('IMPORTACIÓN 273 OK: prioridad PDF, solo sanción, identidad, pagos conservados, validación y ausencia de mutaciones');

assert.equal(esFilaImpuestoGenerador('IMPUESTO','RETENCIÓN'),true);
assert.equal(esFilaImpuestoGenerador('RETENCION','RETENCIÓN EN LA FUENTE'),true);
assert.equal(esFilaImpuestoGenerador('RETENCIÓN','RETENCION'),true);
assert.equal(esFilaImpuestoGenerador('RETENCION','RENTA'),false);
assert.equal(esFilaImpuestoGenerador('RENTA','RENTA'),false);
assert.equal(esFilaImpuestoGenerador('SANCION','RETENCIÓN'),false);
assert.equal(esFilaImpuestoGenerador('INTERESES','RETENCIÓN'),false);
console.log('PDF RETENCIÓN 280 OK: IMPUESTO/RETENCIÓN reconocidos sin alterar otros conceptos');
