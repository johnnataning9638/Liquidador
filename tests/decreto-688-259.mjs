import assert from 'node:assert/strict';
import fs from 'node:fs';
import {MotorLiquidacion} from '../js/motor-liquidacion-base.js';

const m=new MotorLiquidacion({tasasMoratorias:[]});
m.tasaPorFecha=()=>0.2476;
m.beneficioPorTipo=()=>null;
const tasa=(fecha,tipo='TASA DIAN')=>m.tasaEspecial(tipo,fecha).tasa;
assert.equal(tasa('2020-05-21'),0.2476,'21 mayo fuera del decreto');
assert.equal(tasa('2020-05-22'),0.1819,'22 mayo dentro del decreto');
assert.equal(tasa('2020-06-15'),0.1812,'junio IBC');
assert.equal(tasa('2020-07-15'),0.1812,'julio IBC');
assert.equal(tasa('2020-08-15'),0.1829,'agosto IBC');
assert.equal(tasa('2020-09-15'),0.1835,'septiembre IBC');
assert.equal(tasa('2020-10-15'),0.1809,'octubre IBC');
assert.equal(tasa('2020-11-30'),0.1784,'30 noviembre incluido');
assert.equal(tasa('2020-12-01'),0.2476,'1 diciembre fuera del decreto');
assert.equal(tasa('2020-11-30','ART. 91 LEY 2277'),0.1238,'otro beneficio no modificado');
assert.equal(m.tasaPorFecha('2020-11-30','TASA DIAN'),0.2476,'TIM original intacta');
const calculo=m.interesParaPago(2751000,'2019-09-11','2020-11-30',{tasaFija:tasa('2020-11-30')});
assert.equal(calculo.dias,446);
assert.equal(calculo.valor,598000,'caso DIAN 30/11/2020 debe dar $598.000');
const app=fs.readFileSync('js/app.js','utf8');
const tdj=fs.readFileSync('js/tdj-core-16.33.143.js','utf8');
assert.ok(!app.slice(app.indexOf('const TIPOS=['),app.indexOf('];',app.indexOf('const TIPOS=['))).includes('ART. 1 DECRETO 688'));
assert.ok(!tdj.slice(tdj.indexOf('const TIPOS=['),tdj.indexOf('];',tdj.indexOf('const TIPOS=['))).includes('ART. 1 DECRETO 688'));
assert.ok(app.includes('APLICACIÓN AUTOMÁTICA — DECRETO 688'));
assert.ok(tdj.includes('APLICACIÓN AUTOMÁTICA — DECRETO 688'));
console.log('DECRETO 688 259 OK: tasas oficiales mayo-noviembre, límites, selección automática, TIM intacta, $598.000');
